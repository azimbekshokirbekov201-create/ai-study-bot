def tr(key: str, language: str = "uz") -> str:
    value = TEXT.get(key)
    return value[language == "en"] if value else key.replace("_", " ").title()


def menu_key(text: str | None) -> str | None:
    for key in (*MAIN_ITEMS, "home", "back"):
        if text in TEXT[key]:
            return key
    return None
